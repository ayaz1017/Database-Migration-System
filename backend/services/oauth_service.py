def generate_oauth_state(provider: str, redirect_to: str = "/app") -> str:
    """
    Generate a tamper-proof, signed JWT state parameter to prevent CSRF attacks.
    Embeds the provider, redirect target, random nonce, and expiration.
    """
    clean_redirect = redirect_to if (redirect_to.startswith("/") and not redirect_to.startswith("//")) else "/app"
    payload = {
        "action": "oauth_auth",
        "provider": provider.lower(),
        "redirect_to": clean_redirect,
        "nonce": str(uuid.uuid4()),
        "exp": datetime.utcnow() + timedelta(minutes=15),
    }
    return jwt.encode(payload, SECRET_KEY, algorithm=ALGORITHM)


def validate_oauth_state(state: str, expected_provider: str) -> Optional[Dict[str, Any]]:
    """
    Validate that the incoming state parameter was generated by this server,
    matches the expected provider, and has not expired.
    """
    try:
        payload = jwt.decode(state, SECRET_KEY, algorithms=[ALGORITHM])
        if payload.get("action") != "oauth_auth":
            return None
        if payload.get("provider") != expected_provider.lower():
            return None
        return payload
    except (JWTError, Exception):
        return None


def get_google_auth_url(state: str) -> str:
    """Generate the Google OAuth 2.0 authorization URL."""
    cid = os.environ.get("GOOGLE_CLIENT_ID", GOOGLE_CLIENT_ID).strip()
    cb_url = os.environ.get("GOOGLE_CALLBACK_URL", GOOGLE_CALLBACK_URL).strip()
    params = {
        "client_id": cid,
        "redirect_uri": cb_url,
        "response_type": "code",
        "scope": "openid email profile",
        "access_type": "offline",
        "prompt": "select_account",
        "state": state,
    }
    return f"https://accounts.google.com/o/oauth2/v2/auth?{urllib.parse.urlencode(params)}"


